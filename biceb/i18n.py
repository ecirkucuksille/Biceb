def tr(language: str, key: str, **params: object) -> str:
    template = STRINGS.get(language, STRINGS["tr"]).get(key, key)
    return template.format(**params)


def error_text(language: str, code: str) -> str:
    key, _, detail = code.partition("|")
    if key in STRINGS["tr"]:
        return tr(language, key, column=detail)
    return code
